<?php

namespace Database\Seeders;

use Illuminate\Support\Facades\Storage;
use Illuminate\Support\Str;
use ZipArchive;

/**
 * Generates demo product artwork (GD) and small downloadable demo files
 * so the seeded marketplace looks and behaves like a real one.
 */
class DemoMedia
{
    /**
     * @param  array{0: int, 1: int, 2: int}  $from
     * @param  array{0: int, 1: int, 2: int}  $to
     * @return array{path: string, thumb: string}
     */
    public static function productImage(string $title, string $label, array $from, array $to): array
    {
        $w = 1200;
        $h = 900;
        $img = imagecreatetruecolor($w, $h);

        // Diagonal gradient background.
        for ($y = 0; $y < $h; $y++) {
            $t = $y / $h;
            $color = imagecolorallocate(
                $img,
                (int) ($from[0] + ($to[0] - $from[0]) * $t),
                (int) ($from[1] + ($to[1] - $from[1]) * $t),
                (int) ($from[2] + ($to[2] - $from[2]) * $t),
            );
            imageline($img, 0, $y, $w, $y, $color);
        }

        // Soft decorative shapes.
        imagealphablending($img, true);
        $white = fn (int $alpha) => imagecolorallocatealpha($img, 255, 255, 255, $alpha);
        imagefilledellipse($img, 1050, 120, 520, 520, $white(105));
        imagefilledellipse($img, 120, 820, 380, 380, $white(112));

        // Mock "window" card.
        imagefilledrectangle($img, 170, 240, 1030, 700, $white(20));
        imagefilledrectangle($img, 170, 240, 1030, 290, imagecolorallocatealpha($img, 15, 23, 42, 95));
        foreach ([200, 230, 260] as $x) {
            imagefilledellipse($img, $x, 265, 16, 16, $white(30));
        }
        $muted = imagecolorallocatealpha($img, 148, 163, 184, 60);
        imagefilledrectangle($img, 220, 560, 760, 580, $muted);
        imagefilledrectangle($img, 220, 600, 640, 620, $muted);
        imagefilledrectangle($img, 800, 560, 980, 640, imagecolorallocate($img, $from[0], $from[1], $from[2]));

        // Scale the bitmap font so the title always fits inside the mock window.
        $title = Str::upper(Str::limit($title, 30, ''));
        $scale = max(2, min(5, intdiv(760, max(1, imagefontwidth(5) * strlen($title)))));
        self::bigText($img, $title, 220, 340, $scale, [15, 23, 42]);
        self::bigText($img, Str::upper($label), 220, 470, 3, [100, 116, 139]);

        $main = self::encode($img);
        $thumb = imagecreatetruecolor(600, 450);
        imagecopyresampled($thumb, $img, 0, 0, 0, 0, 600, 450, $w, $h);

        $dir = 'products/images';
        $path = $dir.'/'.Str::random(40).'.webp';
        $thumbPath = $dir.'/thumb_'.Str::random(40).'.webp';
        Storage::disk('public')->put($path, $main);
        Storage::disk('public')->put($thumbPath, self::encode($thumb));

        return ['path' => $path, 'thumb' => $thumbPath];
    }

    public static function categoryImage(string $name, array $color): string
    {
        $img = imagecreatetruecolor(800, 500);
        imagefill($img, 0, 0, imagecolorallocate($img, $color[0], $color[1], $color[2]));
        imagealphablending($img, true);
        imagefilledellipse($img, 700, 80, 400, 400, imagecolorallocatealpha($img, 255, 255, 255, 100));
        self::bigText($img, Str::upper($name), 60, 210, 5, [255, 255, 255]);

        $path = 'categories/'.Str::random(40).'.webp';
        Storage::disk('public')->put($path, self::encode($img));

        return $path;
    }

    /**
     * A small zip "product" stored on the private disk.
     *
     * @return array{path: string, name: string, size: int, type: string, mime: string}
     */
    public static function productFile(string $productName, string $version): array
    {
        $tmp = tempnam(sys_get_temp_dir(), 'knb');
        $zip = new ZipArchive;
        $zip->open($tmp, ZipArchive::OVERWRITE);
        $zip->addFromString('README.txt', "{$productName}\nVersion {$version}\n\nThis is a demo file generated by the KN Bazar seeder.\n");
        $zip->addFromString('LICENSE.txt', "Demo licence - for testing the marketplace download flow only.\n");
        $zip->addFromString('docs/getting-started.md', "# {$productName}\n\n1. Unzip the package.\n2. Follow the documentation.\n");
        $zip->close();

        $path = 'products/files/demo/'.Str::random(40).'.zip';
        Storage::disk('local')->put($path, file_get_contents($tmp));
        $size = filesize($tmp);
        @unlink($tmp);

        return ['path' => $path, 'name' => Str::slug($productName).'.zip', 'size' => (int) $size, 'type' => 'zip', 'mime' => 'application/zip'];
    }

    /**
     * Render GD's built-in bitmap font scaled up for headline text.
     *
     * @param  array{0: int, 1: int, 2: int}  $rgb
     */
    protected static function bigText(\GdImage $canvas, string $text, int $x, int $y, int $scale, array $rgb): void
    {
        $font = 5;
        $tw = imagefontwidth($font) * strlen($text);
        $th = imagefontheight($font);
        $layer = imagecreatetruecolor(max(1, $tw), $th);
        imagesavealpha($layer, true);
        imagefill($layer, 0, 0, imagecolorallocatealpha($layer, 0, 0, 0, 127));
        imagestring($layer, $font, 0, 0, $text, imagecolorallocate($layer, $rgb[0], $rgb[1], $rgb[2]));
        imagecopyresampled($canvas, $layer, $x, $y, 0, 0, $tw * $scale, $th * $scale, $tw, $th);
    }

    protected static function encode(\GdImage $img): string
    {
        ob_start();
        imagewebp($img, null, 85);

        return (string) ob_get_clean();
    }
}
